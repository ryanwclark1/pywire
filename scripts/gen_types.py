#!/usr/bin/env python3
"""Regenerate `pywire/types.py` from the native `postgres-types` table.

Run after upgrading pgwire/postgres-types (needs a built extension):

    uv run maturin develop && uv run python scripts/gen_types.py

`tests/test_types.py` fails until the generated file matches the build.
"""

from __future__ import annotations

import subprocess
from pathlib import Path

from pywire._pywire.types import builtin_types

OUTPUT = Path(__file__).resolve().parent.parent / "pywire" / "types.py"

HEADER = '''"""PostgreSQL built-in type OIDs and wire format codes.

`Type` lists every built-in type the `postgres-types` crate (used by pgwire)
knows, under the same names as its Rust `Type` constants: `Type.INT4`,
`Type.TEXT_ARRAY`, `Type.JSONB`, ... Members are `int`s, so they work
anywhere pywire takes an OID:

```python
from pywire.query import FieldInfo
from pywire.types import Format, Type

FieldInfo("id", type_id=Type.INT8, format=Format.BINARY)
```

Custom and extension types (anything created with `CREATE TYPE`) have
OIDs assigned per database; pass those as plain integers.

This file is generated by `scripts/gen_types.py`; do not edit it by hand.
"""

from __future__ import annotations

from enum import IntEnum

from pywire._pywire.types import array_element as _array_element
from pywire._pywire.types import type_name


class Format(IntEnum):
    """Wire format code of a parameter or result column."""

    TEXT = 0
    """Text format: values are their PostgreSQL text representation."""
    BINARY = 1
    """Binary format: values use the type's binary send/recv encoding."""


class Type(IntEnum):
    """Built-in PostgreSQL type OIDs (`pg_type.oid`)."""

'''

FOOTER = '''
    @property
    def pg_name(self) -> str:
        """PostgreSQL's name for the type, e.g. `"int4"` or `"_text"`."""
        return type_name(self) or self.name.lower()

    @property
    def element(self) -> Type | None:
        """Element type of an array type (`Type.INT4_ARRAY.element` is `INT4`)."""
        oid = _array_element(self)
        return None if oid is None else Type(oid)


__all__ = ["Format", "Type", "type_name"]
'''


def member(name: str) -> str:
    return f"{name[1:].upper()}_ARRAY" if name.startswith("_") else name.upper()


def main() -> None:
    body = "".join(f"    {member(name)} = {oid}\n" for name, oid in builtin_types())
    OUTPUT.write_text(HEADER + body + FOOTER)
    subprocess.run(["ruff", "format", "--quiet", str(OUTPUT)], check=False)
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
